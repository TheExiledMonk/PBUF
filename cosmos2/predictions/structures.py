def _prediction_explanation(name: str) -> str | None:
    """Return the stored explanation for a prediction module, if available."""
    return _PREDICTION_EXPLANATIONS.get(name)


@dataclass(frozen=True)
class PredictionTable:
    """Tabular payload describing a prediction table."""

    name: str
    columns: Sequence[str]
    rows: Sequence[Sequence[Any]]
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "columns": list(self.columns),
            "rows": [[_as_serializable(cell) for cell in row] for row in self.rows],
            "metadata": {k: _as_serializable(v) for k, v in self.metadata.items()},
        }


@dataclass(frozen=True)
class PredictionPlot:
    """Descriptor for a prediction plot series."""

    name: str
    data: dict[str, Sequence[Any]]
    description: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "data": {k: _as_serializable(v) for k, v in self.data.items()},
            "description": self.description,
            "metadata": {k: _as_serializable(v) for k, v in self.metadata.items()},
        }


@dataclass(frozen=True)
class PredictionResult:
    """High-level container for prediction outputs."""

    name: str
    version: str
    metadata: dict[str, Any]
    results: dict[str, Any]
    tables: list[PredictionTable] = field(default_factory=list)
    plots: list[PredictionPlot] = field(default_factory=list)
    status: str = "success"

    def to_dict(self) -> dict[str, Any]:
        metadata = {k: _as_serializable(v) for k, v in self.metadata.items()}
        explanation = _prediction_explanation(self.name)
        if explanation and "explanation" not in metadata:
            metadata["explanation"] = explanation

        return {
            "name": self.name,
            "version": self.version,
            "status": self.status,
            "metadata": metadata,
            "results": {k: _as_serializable(v) for k, v in self.results.items()},
            "tables": [table.to_dict() for table in self.tables],
            "plots": [plot.to_dict() for plot in self.plots],
        }
